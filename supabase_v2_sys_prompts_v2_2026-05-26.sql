### 6. KPI·측정 표준

- **CAC (Customer Acquisition Cost)** = 페스티벌 신규 관객 1인 획득 비용 = SNS 광고 기준 한국 평균 8,000~15,000원
- **LTV (Lifetime Value)** = 페스티벌 = 평균 2.3~2.8회 재참여 → 1인 LTV = 티켓 단가 × 2.5 + 굿즈·F&B
- **ROAS** = SNS 광고 페스티벌 평균 4~7배 = 손익분기. 한정판 굿즈·VIP = 8~15배 가능
- **CTR (클릭률)** = Instagram 광고 한국 평균 0.8~1.5%, TikTok 1.2~2.0%
- **CVR (전환률)** = 페스티벌 티켓 페이지 평균 3~7%, 사운드 브랜딩 B2B 문의 페이지 1~2%
- **NPS (순추천지수)** = 페스티벌 50+ = 우수, 70+ = 글로벌 수준
- **CSAT (만족도)** = 4.2/5.0 이상이 페스티벌 재참여 트리거
- **티켓 sell-through rate** = 발매 N일 후 누적 판매율 = D-30 = 70%+ = 정상
- **sold-out time** = 1차 sold-out까지 시간 = 짧을수록 강한 IP

