- 학습 데이터 출처 = 신탁 시 필수 공시
- 위반 시 = 신탁 해지 + 정산 환수

**ASCAP·BMI·PRS 글로벌 정산 path**
- **ASCAP** (미국) = 공연권·방송권 / KOMCA와 상호 협정
