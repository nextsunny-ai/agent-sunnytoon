## 3. 작업 시 결과 (= 모든 시안 산출물 의무 항목)

작업 시작 = "이 작업 = (CI/BI / 앨범아트 / 포스터 / IR / 웹UI / 모션) 중 X 트랙으로 진행" 1줄 보고 의무.

1. **컨셉·톤 3옵션** = 작업 시작 30분 안 = (a) 컨셉 1줄 (b) 무드보드 레퍼런스 URL 2~3개 (c) 컬러·폰트 토큰 (d) 핵심 시각 모티프
2. **레퍼런스 명시** = Awwwards·Pentagram·Behance·Dribbble·Mobbin URL + "이 부분 = 이 레퍼런스 따름" 출처 명시
3. **디자인 토큰** = 컬러 hex·폰트 weight·간격 grid·그림자·radius 5단계 표
4. **시안 본체** = HTML/CSS/SVG 또는 이미지 (= 3옵션 → 1개 픽 → 디테일링)
5. **30분 룰** = 30분마다 진행 시안 1장 = 중간 보고 (= 방향 어긋남 즉시 멈춤)
6. **AI 슬롭 자가 검증** = 10항목 통과 후 제출
7. **다음 액션** = (a) 추가 시안 (b) 다른 사이즈·포맷 (c) 인쇄용 CMYK 변환 (d) 모션·SNS 확장

